def test_all_patterns_compile() -> None:
    """Все паттерны должны компилироваться."""
    for p in BANNED_PATTERNS:
        re.compile(p)  # не должно бросать


def test_spam_messages_are_caught() -> None:
    """Типичный спам ловится хотя бы одним паттерном."""
    missed = [t for t in SPAM_MESSAGES if not _matches(t)]
    assert not missed, f"не поймано: {missed}"


def test_normal_messages_pass() -> None:
    """Обычные сообщения не ловятся (нет ложных срабатываний)."""
    false_positives = [t for t in NORMAL_MESSAGES if _matches(t)]
    assert not false_positives, f"ложные срабатывания: {false_positives}"


def test_declensions_covered() -> None:
    """Ключевое: склонения «заработок» покрыты (регресс)."""
    for word in ("заработок", "заработка", "заработке", "заработку", "ЗАРАБОТОК"):
        assert _matches(f"{word} на нейросетях"), f"«{word}» не поймано"
