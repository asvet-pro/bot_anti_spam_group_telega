# Ниже этого порога id слишком старые/маленькие — интерполяция ненадёжна,
# такие аккаунты считаем «старыми» (никогда не баним по возрасту).
_MIN_INTERPOLABLE_ID = 5_000_000_000

# Опорные точки для экстраполяции вперёд (id новее последней известной пары).
# Основаны на средней скорости роста id (~1 id на 3.2 мс).
_EXTRAPOLATION_RATE = 1.0 / 0.0327252430  # секунд на единицу id


@dataclass(slots=True)
class NewAccountCheck:
    min_age_days: int

    def is_too_young(self, user: types.User) -> bool:
        """True если аккаунт заведомо свежее min_age_days.

        Если возраст оценить нельзя (id вне диапазона интерполяции) —
        возвращаем False: лучше пропустить спамера, чем забанить живого.
        """
        age = self.estimate_age_days(user.id)
        if age is None:
            return False
        return age < self.min_age_days

    def estimate_age_days(self, user_id: int) -> int | None:
        """Оценка возраста аккаунта в днях.

        None — если id вне диапазона, где оценка достоверна.
        """
        ts = self.estimate_registration_ts(user_id)
        if ts is None:
            return None
        age_sec = time.time() - ts
        # Будущая дата (id из будущего) — считаем 0 дней, но не бан.
        return max(0, int(age_sec // 86400))

    @staticmethod
    def estimate_registration_ts(user_id: int) -> float | None:
        """Оценка unix-времени регистрации по user_id (линейная интерполяция).

        None — если оценка ненадёжна (id слишком малый).
        """
        if user_id < _MIN_INTERPOLABLE_ID:
            return None

        known = _KNOWN_ID_DATES

        # Точное совпадение.
        for uid, ts in known:
            if uid == user_id:
                return float(ts)

        # id между двумя известными точками — интерполяция.
        if known[0][0] < user_id < known[-1][0]:
            for i in range(1, len(known)):
                prev_id, prev_ts = known[i - 1]
                curr_id, curr_ts = known[i]
                if prev_id <= user_id <= curr_id:
                    ratio = (user_id - prev_id) / (curr_id - prev_id)
                    return prev_ts + ratio * (curr_ts - prev_ts)

        # id новее самой свежей известной точки — экстраполяция вперёд.
        if user_id > known[-1][0]:
            last_id, last_ts = known[-1]
            return last_ts + (user_id - last_id) * _EXTRAPOLATION_RATE

        return None
