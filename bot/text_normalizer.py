"""Нормализация текста перед ML-инференсом.

Модели детекторов спама (в частности RUSpam/spam_deberta_v4) обучены на
нормализованном тексте. Нормализация:

- убирает «разрежённое» написание (п.р.и.в.е.т. → привет);
- заменяет гомоглифы (латиница в русском тексте и наоборот) на
  кириллические эквиваленты;
- схлопывает повторяющиеся буквы (приввееееет → привет);
- приводит к нижнему регистру.

Это не только повышает точность модели, но и закрывает классический
обход: спамер пишет «zаработок» (латинская z) или «ЗАРАБОТОК» — без
нормализации такое проходит мимо.
"""
from __future__ import annotations

import re


# Латинские буквы, визуально совпадающие с кириллическими.
_LATIN_TO_CYRILLIC = {
    "a": "а", "b": "в", "c": "с", "d": "д", "e": "е", "f": "ф",
    "g": "г", "h": "н", "i": "і", "j": "ј", "k": "к", "l": "л",
    "m": "м", "n": "п", "o": "о", "p": "р", "q": "к", "r": "г",
    "s": "с", "t": "т", "u": "и", "v": "в", "w": "ш", "x": "х",
    "y": "у", "z": "з",
}

# Обратная карта: кириллица → латиница (для слов, полностью латинских).
_CYRILLIC_TO_LATIN = {v: k for k, v in _LATIN_TO_CYRILLIC.items()}

# Гомоглифы из других алфавитов, встречающиеся в спаме.
_OTHER_HOMOGLYPHS = {
    "ɑ": "а", "α": "а", "а": "а",
    "е": "е", "ё": "е", "ε": "е",
    "о": "о", "ο": "о", "օ": "о",
    "р": "р", "ρ": "р",
    "с": "с", "ϲ": "с", "ᴄ": "с",
    "х": "х", "х": "х",
    "у": "у", "γ": "у",
    "і": "и", "ı": "и",
    "ј": "й",
    "һ": "һ", "ʜ": "н", "н": "н",
}

# Разрежённое написание: буквы через запятую или точку.
_SPACED_LETTERS = re.compile(r"(?<=\w)[.,](?=\w)")

# Повторяющиеся буквы (3+ одинаковых подряд) → одна.
# Схлопываем до одного символа: «приввееееет» → «привет».
_REPEATS = re.compile(r"(.)\1+", re.DOTALL)

# Команды ботов вида /cmd@bot.
_BOT_COMMAND = re.compile(r"/[A-Za-z_][A-Za-z0-9_]*@\w+")

# URL-ы.
_URL = re.compile(r"https?://\S+|www\.\S+|\b\S+\.(?:ru|com|net|org|io|xyz)\b\S*")

# Смайлики-эмодзи и прочая пунктуация без смысловой нагрузки.
_PUNCT = re.compile(r"[^\w\s]", re.UNICODE)


def _mix_script_fix(text: str) -> str:
    """Чинит смешение алфавитов в «словах».

    Токенайзер (WordPiece) считает «zаработок» двумя разными токенами,
    потому что латинская z и кириллическая з — разные символы. Модель
    обучалась на чистом кириллице, поэтому приводим к ней.

    Слово, где ВСЕ буквы латинские, оставляем как есть — «chatGPT»,
    «AI», «SEO» должны остаться латиницей.
    """
    words = text.split()
    out: list[str] = []
    for word in words:
        letters = [c for c in word if c.isalpha()]
        if not letters:
            out.append(word)
            continue

        cyr = sum(1 for c in letters if "а" <= c.lower() <= "я" or c.lower() == "ё")
        lat = sum(1 for c in letters if c.isascii() and c.isalpha())

        if lat > 0 and cyr > 0:
            # Смешанное слово — переводим латиницу в кириллицу.
            out.append(
                "".join(_LATIN_TO_CYRILLIC.get(c.lower(), c) for c in word)
            )
        else:
            out.append(word)
    return " ".join(out)


def normalize_for_ml(text: str) -> str:
    """Нормализует текст перед подачей в модель спама."""
    if not text:
        return ""

    t = text.lower()

    # Гомоглифы из других алфавитов.
    for src, dst in _OTHER_HOMOGLYPHS.items():
        if src in t:
            t = t.replace(src, dst)

    # Смешение алфавитов внутри слова.
    t = _mix_script_fix(t)

    # Разрежённое написание.
    t = _SPACED_LETTERS.sub("", t)

    # Повторяющиеся буквы.
    t = _REPEATS.sub(r"\1", t)

    # Команды ботов и ссылки — убираем (в спаме они не несут смысла,
    # но занимают токены и сбивают модель).
    t = _BOT_COMMAND.sub(" ", t)
    t = _URL.sub(" ", t)

    # Пунктуация.
    t = _PUNCT.sub(" ", t)

    # Схлопываем пробелы.
    t = re.sub(r"\s+", " ", t).strip()

    return t
